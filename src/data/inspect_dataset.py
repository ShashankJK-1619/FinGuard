"""Milestone 1, section C: dataset inspection.

Profiles each raw IEEE-CIS table (row/col counts, dtypes, missingness,
cardinality, constant columns, memory footprint) without materializing
full tables into pandas. Uses DuckDB's SUMMARIZE, which computes
per-column stats (null %, approx distinct count, min/max, etc.) in a
single columnar pass over the CSV.

Run: python -m src.data.inspect_dataset
Output: docs/data_profile.md
"""
from __future__ import annotations

import os
import sys

import duckdb
import pandas as pd

from src.data.config import Paths, load_paths
from src.data.loaders import get_connection, raw_files_present, register_raw_views

# Columns whose full uniqueness is expected and not a data-quality flag.
EXPECTED_UNIQUE_KEYS = {"TransactionID"}

HIGH_CARDINALITY_RATIO = 0.5  # approx_unique / row_count above this is flagged
NEAR_CONSTANT_TOP_SHARE = 0.99  # a single value covering >99% of non-null rows


def summarize_table(con: duckdb.DuckDBPyConnection, table: str) -> pd.DataFrame:
    return con.execute(f"SUMMARIZE SELECT * FROM {table}").fetchdf()


def row_count(con: duckdb.DuckDBPyConnection, table: str) -> int:
    return con.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]


def duplicate_key_count(con: duckdb.DuckDBPyConnection, table: str, key: str = "TransactionID") -> int:
    return con.execute(
        f"SELECT COUNT(*) FROM (SELECT {key} FROM {table} GROUP BY {key} HAVING COUNT(*) > 1)"
    ).fetchone()[0]


def near_constant_share(con: duckdb.DuckDBPyConnection, table: str, column: str) -> float:
    """Share of non-null rows held by the single most common value."""
    result = con.execute(
        f"""
        SELECT COUNT(*) AS c
        FROM {table}
        WHERE "{column}" IS NOT NULL
        GROUP BY "{column}"
        ORDER BY c DESC
        LIMIT 1
        """
    ).fetchone()
    top = result[0] if result else 0
    non_null = con.execute(f'SELECT COUNT(*) FROM {table} WHERE "{column}" IS NOT NULL').fetchone()[0]
    return (top / non_null) if non_null else 0.0


def profile_table(con: duckdb.DuckDBPyConnection, table: str, file_path) -> dict:
    n_rows = row_count(con, table)
    summary = summarize_table(con, table)
    summary["null_percentage"] = pd.to_numeric(summary["null_percentage"], errors="coerce")
    summary["approx_unique"] = pd.to_numeric(summary["approx_unique"], errors="coerce")

    n_cols = len(summary)
    file_size_mb = os.path.getsize(file_path) / (1024 * 1024) if file_path.exists() else None

    dup_keys = duplicate_key_count(con, table) if "TransactionID" in summary["column_name"].values else None

    high_card_cols = summary[
        (summary["approx_unique"] / max(n_rows, 1) > HIGH_CARDINALITY_RATIO)
        & (~summary["column_name"].isin(EXPECTED_UNIQUE_KEYS))
    ]["column_name"].tolist()

    constant_cols = summary[summary["approx_unique"] <= 1]["column_name"].tolist()

    # Near-constant check only run on low-cardinality columns (cheap follow-up query).
    low_card_cols = summary[(summary["approx_unique"] > 1) & (summary["approx_unique"] <= 10)]["column_name"].tolist()
    near_constant_cols = []
    for col in low_card_cols:
        share = near_constant_share(con, table, col)
        if share >= NEAR_CONSTANT_TOP_SHARE:
            near_constant_cols.append((col, round(share, 4)))

    high_missing_cols = summary[summary["null_percentage"] >= 90.0]["column_name"].tolist()

    return {
        "table": table,
        "n_rows": n_rows,
        "n_cols": n_cols,
        "file_size_mb": file_size_mb,
        "duplicate_transaction_ids": dup_keys,
        "summary": summary,
        "high_cardinality_cols": high_card_cols,
        "constant_cols": constant_cols,
        "near_constant_cols": near_constant_cols,
        "high_missing_cols": high_missing_cols,
    }


def target_distribution(con: duckdb.DuckDBPyConnection, table: str = "train_transaction") -> dict | None:
    cols = con.execute(f"SELECT * FROM {table} LIMIT 0").fetchdf().columns
    if "isFraud" not in cols:
        return None
    dist = con.execute(f"SELECT isFraud, COUNT(*) AS n FROM {table} GROUP BY isFraud ORDER BY isFraud").fetchdf()
    total = int(dist["n"].sum())
    dist["pct"] = (dist["n"] / total * 100).round(4)
    return {"counts": dist, "total": total}


def render_markdown(profiles: list[dict], target: dict | None) -> str:
    lines = ["# Data Profile — Milestone 1 Section C", ""]
    lines.append(
        "Generated by `src/data/inspect_dataset.py`. No modeling performed; "
        "this is structural inspection only."
    )
    lines.append("")

    lines.append("## Table Overview")
    lines.append("")
    lines.append("| Table | Rows | Columns | File size (MB) | Duplicate TransactionID rows |")
    lines.append("|---|---|---|---|---|")
    for p in profiles:
        size = f"{p['file_size_mb']:.1f}" if p["file_size_mb"] is not None else "n/a"
        dup = p["duplicate_transaction_ids"] if p["duplicate_transaction_ids"] is not None else "n/a"
        lines.append(f"| {p['table']} | {p['n_rows']:,} | {p['n_cols']} | {size} | {dup} |")
    lines.append("")
    lines.append(
        "Note: file size is on-disk CSV size, not in-memory pandas footprint. "
        "In-memory size depends on the dtypes chosen at load time and is not "
        "computed here to avoid materializing full wide tables into pandas."
    )
    lines.append("")

    if target is not None:
        lines.append("## Target Distribution (`isFraud`, train_transaction)")
        lines.append("")
        lines.append("| isFraud | count | pct |")
        lines.append("|---|---|---|")
        for _, row in target["counts"].iterrows():
            lines.append(f"| {int(row['isFraud'])} | {int(row['n']):,} | {row['pct']}% |")
        lines.append("")
        lines.append(
            "Fraud is a minority class by a wide margin. Accuracy is not a usable "
            "metric here: a model predicting isFraud=0 for every row would score "
            "high accuracy while catching zero fraud. Evaluation in later milestones "
            "must use precision/recall/PR-AUC, not accuracy."
        )
        lines.append("")

    for p in profiles:
        lines.append(f"## Table: `{p['table']}`")
        lines.append("")
        lines.append(f"- High-cardinality columns (approx_unique/rows > {HIGH_CARDINALITY_RATIO}, excluding known keys): "
                      f"{p['high_cardinality_cols'] or 'none'}")
        lines.append(f"- Constant columns (<=1 distinct value): {p['constant_cols'] or 'none'}")
        lines.append(f"- Near-constant columns (one value >= {NEAR_CONSTANT_TOP_SHARE*100:.0f}% of non-null rows): "
                      f"{p['near_constant_cols'] or 'none'}")
        lines.append(f"- Columns with >=90% missing: {p['high_missing_cols'] or 'none'}")
        lines.append("")
        lines.append("<details><summary>Full per-column summary (dtype, null %, approx unique, min/max)</summary>")
        lines.append("")
        cols_to_show = ["column_name", "column_type", "null_percentage", "approx_unique", "min", "max"]
        lines.append(p["summary"][cols_to_show].to_markdown(index=False))
        lines.append("")
        lines.append("</details>")
        lines.append("")

    return "\n".join(lines)


def main() -> int:
    paths: Paths = load_paths()
    present = raw_files_present(paths)
    if not all(present.values()):
        missing = [k for k, v in present.items() if not v]
        print("Missing raw files, cannot inspect:", missing, file=sys.stderr)
        print(f"Place the IEEE-CIS CSVs in {paths.raw_dir}", file=sys.stderr)
        return 1

    con = get_connection()
    register_raw_views(con, paths)

    profiles = []
    for table in ["train_transaction", "test_transaction", "train_identity", "test_identity"]:
        profiles.append(profile_table(con, table, paths.raw_file(table)))

    target = target_distribution(con, "train_transaction")

    report = render_markdown(profiles, target)
    paths.docs_dir.mkdir(parents=True, exist_ok=True)
    out_path = paths.docs_dir / "data_profile.md"
    out_path.write_text(report)
    print(f"Wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
