"""Shared visual style for all FinGuard portfolio charts.

One consistent, restrained style is applied everywhere via `apply_style()`:
a light, near-white "lavender" theme (soft lavender/violet accents, a
near-white canvas, dark plum text, subtle lavender grid/borders) designed
to read cleanly on both GitHub light mode and GitHub dark mode -- the
canvas itself stays light (charts are never flipped to a dark background);
a subtle border drawn around the saved PNG is what separates the image
from a dark page background. No 3D, no gradients, minimal gridlines. No
chart in this package adds any AI-tool branding, watermark, or
"generated by" footer -- the only caption text added is a plain
data-source citation (`add_source_note`), which is provenance
information, not attribution to a tool.
"""
from __future__ import annotations

from pathlib import Path

import matplotlib
import matplotlib.pyplot as plt

from src.portfolio.metrics_config import FIGURES_DIR

matplotlib.use("Agg")

# ---------------------------------------------------------------------------
# Lavender palette (GitHub light/dark-mode friendly: light near-white canvas,
# lavender/violet accents, dark plum text -- never a dark chart background).
# ---------------------------------------------------------------------------
BACKGROUND = "#FCFAFF"
BORDER = "#D8D1F0"
GRID = "#E9E4F5"
TEXT_PRIMARY = "#2B2340"
TEXT_SECONDARY = "#5B5470"

LAVENDER = "#A78BFA"        # primary lavender
LAVENDER_LIGHT = "#C4B5FD"  # secondary / lighter lavender
VIOLET = "#8B5CF6"          # deep violet (strongest accent in the family)
PERIWINKLE = "#B8C0FF"      # cool tertiary accent

# Semantic accents -- used only where they help interpret a threshold,
# a caution/negative finding, or a positive finding; never for ordinary
# categories (keeps the palette lavender-dominant as required).
WARNING = "#FDE68A"         # pale amber, optional fills
AMBER_MUTED = "#C9961A"     # deepened amber for line-weight visibility --
                             # FDE68A has ~1.2:1 contrast against BACKGROUND
                             # (effectively invisible as a 1-2px line), so
                             # threshold/reference lines use this darker
                             # amber from the same family instead
CAUTION = "#E9A8C9"         # muted pink -- flags a cautionary/negative finding
POSITIVE = "#8BD3C7"        # muted teal-green -- flags a positive finding

PALETTE = [VIOLET, LAVENDER, PERIWINKLE, LAVENDER_LIGHT]

# Back-compat aliases: charts built for Step 3 that only need a generic
# "primary / secondary / muted" two-series contrast import these names.
# Re-pointing them here (rather than editing every chart script) keeps the
# palette centralized in one place, per the Step-3 "single source of truth"
# rule. Charts with chart-specific semantic guidance (payments
# control/treatment, architecture module cards, calibration drift, risk
# bands, summary tiles) import the specific constants above directly
# instead of these aliases.
#   NAVY -> muted lavender ("baseline" / "first" series)
#   TEAL -> stronger violet ("preferred" / "second" series)
#   GRAY -> secondary text (reference lines, muted annotation)
NAVY = LAVENDER
TEAL = VIOLET
GRAY = TEXT_SECONDARY
LIGHT_GRAY = GRID


def apply_style() -> None:
    plt.rcParams.update(
        {
            "figure.facecolor": BACKGROUND,
            "axes.facecolor": BACKGROUND,
            "savefig.facecolor": BACKGROUND,
            "axes.edgecolor": BORDER,
            "axes.labelcolor": TEXT_PRIMARY,
            "text.color": TEXT_PRIMARY,
            "xtick.color": TEXT_PRIMARY,
            "ytick.color": TEXT_PRIMARY,
            "axes.grid": True,
            "grid.color": GRID,
            "grid.linewidth": 0.7,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "patch.edgecolor": TEXT_SECONDARY,
            "patch.force_edgecolor": True,
            "patch.linewidth": 1.0,
            "font.family": "sans-serif",
            "font.sans-serif": ["Helvetica", "Arial", "DejaVu Sans"],
            "font.size": 11,
            "axes.titlesize": 14,
            "axes.titleweight": "bold",
            "axes.labelsize": 11.5,
            "xtick.labelsize": 10.5,
            "ytick.labelsize": 10.5,
            "legend.fontsize": 10.5,
            "legend.frameon": False,
            "legend.labelcolor": TEXT_PRIMARY,
            "figure.dpi": 150,
            "savefig.dpi": 200,
        }
    )


def add_source_note(fig, text: str) -> None:
    """Small muted provenance caption at the bottom of the figure. Not a
    tool/AI attribution -- strictly a data-source citation for reproducibility."""
    fig.text(
        0.01,
        0.01,
        text,
        ha="left",
        va="bottom",
        fontsize=8,
        color=TEXT_SECONDARY,
        style="italic",
        wrap=True,
    )


def _hex_to_rgb(hex_color: str) -> tuple[int, int, int]:
    h = hex_color.lstrip("#")
    return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4))  # noqa: E203


def save_figure(fig, filename: str) -> Path:
    """Save a figure, then stamp a subtle lavender-border frame around the
    final PNG so it reads cleanly as a distinct card on GitHub's dark-mode
    page background without the chart itself switching to a dark theme."""
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    out_path = FIGURES_DIR / filename
    fig.savefig(out_path, bbox_inches="tight")
    plt.close(fig)

    from PIL import Image, ImageDraw

    img = Image.open(out_path).convert("RGB")
    draw = ImageDraw.Draw(img)
    w, h = img.size
    draw.rectangle([0, 0, w - 1, h - 1], outline=_hex_to_rgb(BORDER), width=3)
    img.save(out_path)
    return out_path


def annotate_bars(ax, bars, fmt="{:.3f}", offset=0.01, color=None, fontsize=10.5):
    """Directly label each bar with its value (readability rule: don't make
    the reader infer values from axis position alone)."""
    if color is None:
        color = TEXT_PRIMARY
    for bar in bars:
        height = bar.get_height()
        ax.annotate(
            fmt.format(height),
            xy=(bar.get_x() + bar.get_width() / 2, height),
            xytext=(0, offset * 100),
            textcoords="offset points",
            ha="center",
            va="bottom",
            fontsize=fontsize,
            color=color,
        )
